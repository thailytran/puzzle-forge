"""`forge layout demo`: a sample interior that exercises the Typst pipeline."""

from __future__ import annotations

from forge.core.seeds import make_rng
from forge.layout.document import LayoutDoc, Page, make_layout


def _letters(seed: int, n: int) -> list[list[str]]:
    rng = make_rng(seed)
    return [[chr(ord("A") + rng.randrange(26)) for _ in range(n)] for _ in range(n)]


def demo_layout(trim: str = "8.5x11", large_print: bool = False, seed: int = 1) -> LayoutDoc:
    grid_n = 10 if large_print else 14
    cell = 0.45 if large_print else 0.38
    pages = [
        Page(kind="title"),
        Page(
            kind="copyright",
            header=False,
            blocks=[
                {"kind": "spacer", "height_in": 5.0},
                {
                    "kind": "paragraph",
                    "text": "Copyright © 2026 Puzzle Forge. All rights reserved.",
                },
                {"kind": "paragraph", "text": "This is a layout demo generated by Puzzle Forge."},
            ],
        ),
        Page(
            kind="text",
            title="Contents",
            blocks=[
                {
                    "kind": "toc",
                    "entries": [
                        {"title": "How to Play", "page": 4},
                        {"title": "Sample Grid", "page": 5},
                        {"title": "Notes", "page": 6},
                    ],
                }
            ],
        ),
        Page(
            kind="text",
            title="How to Play",
            blocks=[
                {
                    "kind": "paragraph",
                    "text": "Find every word from the list hidden in the grid. Words can run "
                    "across, down or diagonally. Circle each word when you find it.",
                },
                {"kind": "list", "items": ["Start with the longest words.", "Have fun!"]},
            ],
        ),
        Page(
            kind="puzzle",
            title="Sample Grid",
            blocks=[
                {
                    "kind": "letter_grid",
                    "rows": _letters(seed, grid_n),
                    "cell_in": cell,
                    "font_pt": 18 if large_print else 14,
                },
            ],
        ),
    ]
    return make_layout(
        title="Puzzle Forge Layout Demo",
        subtitle="Typst pipeline check",
        author="Puzzle Forge",
        trim=trim,
        pages=pages,
        large_print=large_print,
        min_pages=0,
    )
