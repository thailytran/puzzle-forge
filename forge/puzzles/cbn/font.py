def is_icon(code: str) -> bool:
    return code.startswith("@")


def known(code: str) -> bool:
    """True when `code` can be shown by a mosaic: letters / digits / symbols, or "@icon"."""
    if is_icon(code):
        return code[1:] in ICONS
    return bool(code) and all(ch in GLYPHS for ch in code)


def bitmap_of(code: str) -> list[list[int]]:
    """Pixel rows of a code: an icon, or its glyphs side by side with one empty column between."""
    if is_icon(code):
        return [[int(c) for c in row] for row in ICONS[code[1:]]]
    rows: list[list[int]] = [[] for _ in range(H)]
    for i, ch in enumerate(code):
        for r in range(H):
            rows[r] += ([0] if i else []) + [int(c) for c in GLYPHS[ch][r]]
    return rows


def decode(block: list[list[int]]) -> str:
    """Code shown by a pixel block of the right size ("?" when it is not an exact picture)."""
    h, w = len(block), len(block[0])
    if (w, h) == (ICON, ICON):
        for name, rows in ICONS.items():
            if all(block[r][c] == int(rows[r][c]) for r in range(ICON) for c in range(ICON)):
                return "@" + name
        return "?"
    if h != H or (w + 1) % (W + 1):
        return "?"
    out = []
    for k in range((w + 1) // (W + 1)):
        x0 = k * (W + 1)
        ch, err = match([row[x0 : x0 + W] for row in block])
        if err or (k and any(row[x0 - 1] for row in block)):
            return "?"
        out.append(ch)
    return "".join(out)


def bitmap(ch: str) -> list[list[int]]:
    return [[int(c) for c in row] for row in GLYPHS[ch]]


def match(block: list[list[int]]) -> tuple[str, int]:
    """Best glyph for a 5x7 0/1 block and the number of mismatching pixels."""
    best, score = "?", 99
    for ch in GLYPHS:
        bm = bitmap(ch)
        diff = sum(bm[r][c] != block[r][c] for r in range(H) for c in range(W))
        if diff < score:
            best, score = ch, diff
    return best, score
