W, H = 5, 7


def bitmap(ch: str) -> list[list[int]]:
    return [[int(c) for c in row] for row in GLYPHS[ch]]


def match(block: list[list[int]]) -> tuple[str, int]:
    """Best glyph for a 5x7 0/1 block and the number of mismatching pixels."""
    best, score = "?", 99
    for ch in GLYPHS:
        bm = bitmap(ch)
        diff = sum(bm[r][c] != block[r][c] for r in range(H) for c in range(W))
        if diff < score:
            best, score = ch, diff
    return best, score
